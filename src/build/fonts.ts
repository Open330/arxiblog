import { copyFileSync, existsSync, mkdirSync, statSync, writeFileSync } from "fs";
import { dirname, join } from "path";

/**
 * Pretendard is the only web font the generated site loads, and it is served
 * from the site's own origin (the CSP allows `font-src 'self'`), never a CDN.
 *
 * The full Korean face is ~750 KB per weight, so shipping Regular + Bold cost
 * every reader 1.5 MB. Upstream publishes the same 1.3.9 font pre-split into 92
 * `unicode-range` chunks per weight, so a browser downloads only the chunks
 * that the page's text actually falls into — while the union of the chunks
 * still covers all 11,172 Hangul syllables, which matters because chat answers
 * are generated at runtime and can contain characters no built page used.
 *
 * When that package is unavailable the build falls back to the two full faces,
 * i.e. exactly the previous behaviour.
 */

const DYNAMIC_SUBSET_CSS = "pretendard/dist/web/static/pretendard-dynamic-subset.css";
const FULL_FACE = {
  400: "@fontsource/pretendard/files/pretendard-latin-400-normal.woff2",
  700: "@fontsource/pretendard/files/pretendard-latin-700-normal.woff2",
} as const;
/** Despite the `-latin-` file name this face carries the complete Hangul set. */
const FULL_FACE_FILENAME = { 400: "Pretendard-Regular.woff2", 700: "Pretendard-Bold.woff2" } as const;
const WEIGHTS = [400, 700] as const;

/** Upstream ships the OFL text with the @fontsource package, not with `pretendard`. */
const LICENSE_PACKAGE = "@fontsource/pretendard";

export type FontMode = "dynamic-subset" | "full";

export interface FontBuildResult {
  mode: FontMode;
  /** Number of woff2 files written under static/vendor/pretendard/. */
  fileCount: number;
  /** Total bytes of those files (what a deploy stores, not what a page loads). */
  totalBytes: number;
  /** Bytes a page must load to render Latin-only text — the unavoidable floor. */
  cssBytes: number;
}

export interface FontFace {
  weight: number;
  /** Path relative to static/fonts.css. */
  url: string;
  unicodeRange?: string;
  sourcePath: string;
}

function resolveOptional(specifier: string): string | null {
  try {
    return Bun.resolveSync(specifier, import.meta.dir);
  } catch {
    return null;
  }
}

function resolveRequired(specifier: string): string {
  const resolved = resolveOptional(specifier);
  if (!resolved) {
    throw new Error(`정적 자산 패키지를 찾을 수 없습니다 (${specifier}). 먼저 bun install을 실행하세요.`);
  }
  return resolved;
}

/**
 * Read upstream's dynamic-subset stylesheet and keep only the weights this site
 * renders. Returns null (→ full faces) if anything about the package looks
 * different from what this code expects, so a bad parse can never publish a
 * stylesheet pointing at files that were not copied.
 */
export function readDynamicSubsetFaces(cssPath: string): FontFace[] | null {
  let css: string;
  try {
    css = require("fs").readFileSync(cssPath, "utf8") as string;
  } catch {
    return null;
  }
  const fileDir = join(dirname(cssPath), "woff2-dynamic-subset");
  const faces: FontFace[] = [];
  for (const block of css.split("@font-face").slice(1)) {
    const weight = Number(/font-weight:\s*(\d+)/.exec(block)?.[1]);
    if (!WEIGHTS.includes(weight as (typeof WEIGHTS)[number])) continue;
    const file = /url\(\.\/woff2-dynamic-subset\/([\w.-]+\.woff2)\)/.exec(block)?.[1];
    const unicodeRange = /unicode-range:\s*([^;}]+);/.exec(block)?.[1]?.trim();
    if (!file || !unicodeRange) return null;
    const sourcePath = join(fileDir, file);
    if (!existsSync(sourcePath)) return null;
    faces.push({ weight, url: `vendor/pretendard/subset/${file}`, unicodeRange, sourcePath });
  }
  // Both weights must be present and split the same way; an asymmetric result
  // would silently render one weight with fewer glyphs than the other.
  const perWeight = WEIGHTS.map((w) => faces.filter((f) => f.weight === w).length);
  if (perWeight.some((count) => count === 0) || new Set(perWeight).size !== 1) return null;
  return faces;
}

/** One `@font-face` rule per line — the file is machine-generated, not edited. */
export function renderFontCss(faces: FontFace[], mode: FontMode): string {
  const header =
    mode === "dynamic-subset"
      ? `/* Generated by src/build/fonts.ts — do not edit.\n   Pretendard 1.3.9 dynamic subset (${faces.length} faces); see vendor/pretendard/LICENSE.txt (OFL-1.1). */`
      : `/* Generated by src/build/fonts.ts — do not edit.\n   Pretendard 1.3.9 full Korean faces; see vendor/pretendard/LICENSE.txt (OFL-1.1). */`;
  const rules = faces.map((face) =>
    [
      "@font-face{",
      `font-family:"Pretendard";`,
      "font-style:normal;",
      "font-display:swap;",
      `font-weight:${face.weight};`,
      `src:url("${face.url}") format("woff2");`,
      // Upstream separates the ~6,900 range entries with ", "; stripping the
      // spaces trims several KB from a stylesheet that blocks first paint.
      face.unicodeRange ? `unicode-range:${face.unicodeRange.replace(/,\s+/g, ",")};` : "",
      "}",
    ].join("")
  );
  return `${header}\n${rules.join("\n")}\n`;
}

/**
 * Write the site's font files and the stylesheet that points at them.
 *
 * Called after the static directory has been copied, because it replaces the
 * checked-in `static/fonts.css` placeholder with the generated stylesheet.
 */
export function prepareFonts(staticDir: string): FontBuildResult {
  const vendorDir = join(staticDir, "vendor", "pretendard");
  mkdirSync(vendorDir, { recursive: true });
  copyFileSync(
    join(dirname(resolveRequired(`${LICENSE_PACKAGE}/package.json`)), "LICENSE"),
    join(vendorDir, "LICENSE.txt")
  );

  const subsetCssPath = resolveOptional(DYNAMIC_SUBSET_CSS);
  const faces = subsetCssPath ? readDynamicSubsetFaces(subsetCssPath) : null;

  let written: FontFace[];
  if (faces) {
    const subsetDir = join(vendorDir, "subset");
    mkdirSync(subsetDir, { recursive: true });
    for (const face of faces) copyFileSync(face.sourcePath, join(subsetDir, face.url.split("/").pop()!));
    written = faces;
  } else {
    // Regular + bold cover the UI's body and emphasis/headline use. Intermediate
    // weights map to the nearest local face; the system stack stays the no-JS
    // fallback.
    written = WEIGHTS.map((weight) => {
      const sourcePath = resolveRequired(FULL_FACE[weight]);
      copyFileSync(sourcePath, join(vendorDir, FULL_FACE_FILENAME[weight]));
      return { weight, url: `vendor/pretendard/${FULL_FACE_FILENAME[weight]}`, sourcePath };
    });
  }

  const mode: FontMode = faces ? "dynamic-subset" : "full";
  const css = renderFontCss(written, mode);
  writeFileSync(join(staticDir, "fonts.css"), css);
  return {
    mode,
    fileCount: written.length,
    totalBytes: written.reduce((sum, face) => sum + statSync(face.sourcePath).size, 0),
    cssBytes: Buffer.byteLength(css),
  };
}
